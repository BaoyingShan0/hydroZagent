import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPOSITORY_ROOT = fileURLToPath(new URL("../", import.meta.url));
const CONTRACT_DIRECTORY = join(REPOSITORY_ROOT, "contracts", "hcs", "v1");
const SCHEMA_PATH = join(CONTRACT_DIRECTORY, "schema.json");
const OPENAPI_PATH = join(CONTRACT_DIRECTORY, "openapi.json");
const ACCEPTED_FIXTURES_PATH = join(CONTRACT_DIRECTORY, "fixtures", "accepted.json");
const REJECTED_FIXTURES_PATH = join(CONTRACT_DIRECTORY, "fixtures", "rejected.json");

export const GENERATED_CONTRACT_PATHS = [
	join(REPOSITORY_ROOT, "apps", "server", "src", "contracts", "generated.ts"),
	join(REPOSITORY_ROOT, "apps", "desktop", "src", "shared", "hcsContracts.generated.ts"),
	join(REPOSITORY_ROOT, "packages", "coding-agent", "src", "modes", "rpc", "managedProvider.generated.ts"),
];

function readJson(path) {
	return JSON.parse(readFileSync(path, "utf8"));
}

function renderLiteral(value) {
	return JSON.stringify(value);
}

function renderUnion(values, indent) {
	const rendered = values.map((value) => renderSchemaType(value, indent));
	const oneLine = rendered.join(" | ");
	if (oneLine.length <= 70 && !oneLine.includes("\n")) return oneLine;
	return `\n${rendered.map((value) => `${indent}\t| ${value}`).join("\n")}`;
}

function renderPropertyName(name) {
	return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

function renderObject(schema, indent) {
	const properties = schema.properties ?? {};
	const required = new Set(schema.required ?? []);
	const entries = Object.entries(properties);
	if (entries.length === 0) {
		return schema.additionalProperties === false ? "Record<string, never>" : "Record<string, unknown>";
	}

	const childIndent = `${indent}\t`;
	const lines = entries.map(([name, propertySchema]) => {
		const optional = required.has(name) ? "" : "?";
		const propertyType = renderSchemaType(propertySchema, childIndent);
		const separator = propertyType.startsWith("\n") ? ":" : ": ";
		return `${childIndent}${renderPropertyName(name)}${optional}${separator}${propertyType};`;
	});
	if (schema.additionalProperties === true) lines.push(`${childIndent}[key: string]: unknown;`);
	if (schema.additionalProperties && typeof schema.additionalProperties === "object") {
		lines.push(`${childIndent}[key: string]: ${renderSchemaType(schema.additionalProperties, childIndent)};`);
	}
	return `{\n${lines.join("\n")}\n${indent}}`;
}

function renderSchemaType(schema, indent = "") {
	if (typeof schema !== "object" || schema === null) return "unknown";
	if (typeof schema.$ref === "string") return schema.$ref.split("/").at(-1).replaceAll("~1", "/").replaceAll("~0", "~");
	if (Object.hasOwn(schema, "const")) return renderLiteral(schema.const);
	if (Array.isArray(schema.enum)) return renderUnion(schema.enum.map((value) => ({ const: value })), indent);
	if (Array.isArray(schema.oneOf)) return renderUnion(schema.oneOf, indent);
	if (Array.isArray(schema.anyOf)) return renderUnion(schema.anyOf, indent);
	if (Array.isArray(schema.type)) {
		return renderUnion(schema.type.map((type) => ({ ...schema, type })), indent);
	}
	if (schema.type === "object" || schema.properties) return renderObject(schema, indent);
	if (schema.type === "array") return `Array<${renderSchemaType(schema.items ?? {}, indent)}>`;
	if (schema.type === "string") return "string";
	if (schema.type === "integer" || schema.type === "number") return "number";
	if (schema.type === "boolean") return "boolean";
	if (schema.type === "null") return "null";
	return "unknown";
}

export function loadContractSource() {
	return {
		schema: readJson(SCHEMA_PATH),
		openapi: readJson(OPENAPI_PATH),
		acceptedFixtures: readJson(ACCEPTED_FIXTURES_PATH),
		rejectedFixtures: readJson(REJECTED_FIXTURES_PATH),
	};
}

export function contractHash(schema) {
	return createHash("sha256").update(`${JSON.stringify(schema)}\n`).digest("hex");
}

export function renderGeneratedContract(schema) {
	const definitions = schema.$defs ?? {};
	const hash = contractHash(schema);
	const serializedSchema = JSON.stringify(schema).replaceAll("`", "\\`").replaceAll("${", "\\${");
	const types = Object.entries(definitions)
		.map(([name, definition]) => {
			const rendered = renderSchemaType(definition);
			const separator = rendered.startsWith("\n") ? "=" : "= ";
			return `export type ${name} ${separator}${rendered};`;
		})
		.join("\n\n");
	return `// Generated by scripts/generate-hcs-contracts.mjs. Do not edit manually.\n\nexport const HCS_CONTRACT_VERSION = "1";\nexport const HCS_CONTRACT_SHA256 = "${hash}";\nexport const HCS_SCHEMA_JSON = String.raw\`${serializedSchema}\`;\n\n${types}\n`;
}

export function generateContracts({ check = false } = {}) {
	const { schema } = loadContractSource();
	const generated = renderGeneratedContract(schema);
	const drifted = [];
	for (const path of GENERATED_CONTRACT_PATHS) {
		if (check) {
			if (!existsSync(path) || readFileSync(path, "utf8") !== generated) drifted.push(path);
			continue;
		}
		mkdirSync(dirname(path), { recursive: true });
		writeFileSync(path, generated, "utf8");
	}
	return drifted;
}

function resolveSchemaReference(rootSchema, reference) {
	if (!reference.startsWith("#/$defs/")) return undefined;
	const name = reference.slice("#/$defs/".length).replaceAll("~1", "/").replaceAll("~0", "~");
	return rootSchema.$defs?.[name];
}

function isPlainObject(value) {
	return typeof value === "object" && value !== null && !Array.isArray(value);
}

function formatMatches(format, value) {
	if (format === "uuid") {
		return /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(value);
	}
	if (format === "date-time") return /^\d{4}-\d{2}-\d{2}T/.test(value) && Number.isFinite(Date.parse(value));
	return true;
}

function validateNode(rootSchema, schema, value, path, errors) {
	if (!isPlainObject(schema)) return;
	if (typeof schema.$ref === "string") {
		const referenced = resolveSchemaReference(rootSchema, schema.$ref);
		if (!referenced) {
			errors.push(`${path}: unresolved reference ${schema.$ref}`);
			return;
		}
		validateNode(rootSchema, referenced, value, path, errors);
		return;
	}
	if (Array.isArray(schema.oneOf)) {
		const matches = schema.oneOf.filter((candidate) => {
			const candidateErrors = [];
			validateNode(rootSchema, candidate, value, path, candidateErrors);
			return candidateErrors.length === 0;
		});
		if (matches.length !== 1) errors.push(`${path}: expected exactly one schema match, received ${matches.length}`);
		return;
	}
	if (Array.isArray(schema.anyOf)) {
		const matches = schema.anyOf.some((candidate) => {
			const candidateErrors = [];
			validateNode(rootSchema, candidate, value, path, candidateErrors);
			return candidateErrors.length === 0;
		});
		if (!matches) errors.push(`${path}: expected at least one schema match`);
		return;
	}
	if (Object.hasOwn(schema, "const") && !Object.is(schema.const, value)) {
		errors.push(`${path}: expected ${JSON.stringify(schema.const)}`);
		return;
	}
	if (Array.isArray(schema.enum) && !schema.enum.some((candidate) => Object.is(candidate, value))) {
		errors.push(`${path}: value is not in enum`);
		return;
	}

	if (schema.type === "null") {
		if (value !== null) errors.push(`${path}: expected null`);
		return;
	}
	if (schema.type === "string") {
		if (typeof value !== "string") {
			errors.push(`${path}: expected string`);
			return;
		}
		if (schema.minLength !== undefined && value.length < schema.minLength) errors.push(`${path}: shorter than minLength`);
		if (schema.maxLength !== undefined && value.length > schema.maxLength) errors.push(`${path}: longer than maxLength`);
		if (schema.pattern !== undefined && !new RegExp(schema.pattern, "u").test(value)) errors.push(`${path}: pattern mismatch`);
		if (schema.format !== undefined && !formatMatches(schema.format, value)) errors.push(`${path}: format mismatch`);
		return;
	}
	if (schema.type === "boolean") {
		if (typeof value !== "boolean") errors.push(`${path}: expected boolean`);
		return;
	}
	if (schema.type === "integer" || schema.type === "number") {
		if (typeof value !== "number" || !Number.isFinite(value) || (schema.type === "integer" && !Number.isInteger(value))) {
			errors.push(`${path}: expected ${schema.type}`);
			return;
		}
		if (schema.minimum !== undefined && value < schema.minimum) errors.push(`${path}: lower than minimum`);
		if (schema.maximum !== undefined && value > schema.maximum) errors.push(`${path}: higher than maximum`);
		return;
	}
	if (schema.type === "array") {
		if (!Array.isArray(value)) {
			errors.push(`${path}: expected array`);
			return;
		}
		if (schema.minItems !== undefined && value.length < schema.minItems) errors.push(`${path}: fewer than minItems`);
		if (schema.maxItems !== undefined && value.length > schema.maxItems) errors.push(`${path}: more than maxItems`);
		if (schema.uniqueItems === true && new Set(value.map((item) => JSON.stringify(item))).size !== value.length) {
			errors.push(`${path}: duplicate array items`);
		}
		for (const [index, item] of value.entries()) validateNode(rootSchema, schema.items ?? {}, item, `${path}[${index}]`, errors);
		return;
	}
	if (schema.type === "object" || schema.properties) {
		if (!isPlainObject(value)) {
			errors.push(`${path}: expected object`);
			return;
		}
		for (const required of schema.required ?? []) {
			if (!Object.hasOwn(value, required)) errors.push(`${path}.${required}: required property missing`);
		}
		const properties = schema.properties ?? {};
		for (const [name, propertyValue] of Object.entries(value)) {
			if (Object.hasOwn(properties, name)) {
				validateNode(rootSchema, properties[name], propertyValue, `${path}.${name}`, errors);
			} else if (schema.additionalProperties === false) {
				errors.push(`${path}.${name}: additional property is forbidden`);
			} else if (isPlainObject(schema.additionalProperties)) {
				validateNode(rootSchema, schema.additionalProperties, propertyValue, `${path}.${name}`, errors);
			}
		}
	}
}

export function validateFixture(schema, schemaName, value) {
	const definition = schema.$defs?.[schemaName];
	if (!definition) return [`$: unknown schema ${schemaName}`];
	const errors = [];
	validateNode(schema, definition, value, "$", errors);
	return errors;
}

function resolveJsonPointer(document, pointer) {
	if (pointer === "#") return document;
	if (!pointer.startsWith("#/")) return undefined;
	return pointer
		.slice(2)
		.split("/")
		.map((part) => part.replaceAll("~1", "/").replaceAll("~0", "~"))
		.reduce((current, part) => (isPlainObject(current) ? current[part] : undefined), document);
}

export function validateOpenApiReferences(openapi, schema) {
	const errors = [];
	const visit = (value, path) => {
		if (Array.isArray(value)) {
			for (const [index, item] of value.entries()) visit(item, `${path}[${index}]`);
			return;
		}
		if (!isPlainObject(value)) return;
		if (typeof value.$ref === "string") {
			const target = value.$ref.startsWith("./schema.json")
				? resolveJsonPointer(schema, value.$ref.slice("./schema.json".length))
				: resolveJsonPointer(openapi, value.$ref);
			if (target === undefined) errors.push(`${path}: unresolved OpenAPI reference ${value.$ref}`);
		}
		for (const [key, child] of Object.entries(value)) visit(child, `${path}.${key}`);
	};
	visit(openapi, "$openapi");
	return errors;
}

export function verifyContractFixtures() {
	const { schema, openapi, acceptedFixtures, rejectedFixtures } = loadContractSource();
	const failures = [];
	for (const [index, fixture] of acceptedFixtures.entries()) {
		const errors = validateFixture(schema, fixture.schema, fixture.value);
		if (errors.length > 0) failures.push(`accepted[${index}] ${fixture.schema}: ${errors.join("; ")}`);
	}
	for (const [index, fixture] of rejectedFixtures.entries()) {
		const errors = validateFixture(schema, fixture.schema, fixture.value);
		if (errors.length === 0) failures.push(`rejected[${index}] ${fixture.schema}: unexpectedly accepted (${fixture.reason})`);
	}
	failures.push(...validateOpenApiReferences(openapi, schema));
	return failures;
}
